import { ADMIN_USERNAME, dialog, expect, newSignedOutContext, signIn, test, unique } from "./fixtures"

const PASSWORD = "user-password-123"

test("shows the signed-in user without self-destructive actions", async ({ page }) => {
  await page.goto("/settings/users")
  const row = page.getByRole("row").filter({ hasText: ADMIN_USERNAME }).filter({ hasText: "You" })
  await expect(row).toBeVisible()
  await expect(row.getByRole("button", { name: "Edit" })).toBeVisible()
  await expect(row.getByRole("button", { name: "Delete" })).toHaveCount(0)
  await expect(row.getByRole("button", { name: "Reset password" })).toHaveCount(0)
})

test("creates a user who can sign in", async ({ page, browser, baseURL }) => {
  const username = unique("user")
  await page.goto("/settings/users")
  await page.getByRole("button", { name: "New user" }).click()
  await expect(dialog(page)).toContainText("New user")

  await dialog(page).getByLabel("Username").fill("x")
  await dialog(page)
    .getByLabel(/^Password/)
    .fill("short")
  await dialog(page).getByRole("button", { name: "Create user" }).click()
  await expect(dialog(page).getByText("Use 3–64 letters, numbers, '.', '_' or '-'")).toBeVisible()
  await expect(dialog(page).getByText("Use at least 12 characters")).toBeVisible()

  await dialog(page).getByLabel("Username").fill(username)
  await dialog(page)
    .getByLabel(/^Password/)
    .fill(PASSWORD)
  await dialog(page).getByLabel("First name").fill("Grace")
  await dialog(page).getByLabel("Email").fill(`${username}@example.com`)
  await dialog(page).getByRole("button", { name: "Create user" }).click()
  await expect(dialog(page)).toBeHidden()
  await expect(page.getByText("User created")).toBeVisible()
  const row = page.getByRole("row").filter({ hasText: username })
  await expect(row).toContainText("Grace")
  await expect(row).toContainText(`${username}@example.com`)

  const context = await newSignedOutContext(browser, baseURL)
  const other = await context.newPage()
  await signIn(other, username, PASSWORD)
  await expect(other.getByRole("heading", { name: "Dashboard" })).toBeVisible()
  await context.close()
})

test("reports a duplicate username", async ({ page, api }) => {
  const username = unique("taken")
  await api.createUser(username, PASSWORD)
  await page.goto("/settings/users")
  await page.getByRole("button", { name: "New user" }).click()
  await dialog(page).getByLabel("Username").fill(username.toUpperCase())
  await dialog(page)
    .getByLabel(/^Password/)
    .fill(PASSWORD)
  await dialog(page).getByRole("button", { name: "Create user" }).click()
  await expect(dialog(page).getByRole("alert")).toContainText("user already exists")
  // Escape closes the dialog.
  await page.keyboard.press("Escape")
  await expect(dialog(page)).toBeHidden()
})

test("edits a user", async ({ page, api }) => {
  const username = unique("edituser")
  await api.createUser(username, PASSWORD)
  await page.goto("/settings/users")
  await page.getByRole("row").filter({ hasText: username }).getByRole("button", { name: "Edit" }).click()
  await expect(dialog(page)).toContainText("Edit user")
  await expect(dialog(page).getByLabel(/^Password/)).toHaveCount(0)
  await dialog(page).getByLabel("Last name").fill("Hopper")
  await dialog(page).getByRole("button", { name: "Save user" }).click()
  await expect(page.getByText("User saved")).toBeVisible()
  await expect(page.getByRole("row").filter({ hasText: username })).toContainText("Hopper")
})

test("resets another user's password", async ({ page, api, browser, baseURL }) => {
  const username = unique("resetuser")
  await api.createUser(username, PASSWORD)
  await page.goto("/settings/users")
  await page.getByRole("row").filter({ hasText: username }).getByRole("button", { name: "Reset password" }).click()
  await expect(dialog(page)).toContainText(`Reset password for ${username}`)
  await expect(dialog(page).getByLabel("Current password")).toHaveCount(0)
  await dialog(page)
    .getByLabel(/^New password/)
    .fill("brand-new-password")
  await dialog(page).getByLabel("Confirm new password").fill("brand-new-password")
  await dialog(page).getByRole("button", { name: "Reset password" }).click()
  await expect(page.getByText("Password reset. The user was signed out.")).toBeVisible()

  const context = await newSignedOutContext(browser, baseURL)
  const other = await context.newPage()
  await signIn(other, username, PASSWORD)
  await expect(other.getByRole("alert")).toHaveText("Invalid username or password.")
  await signIn(other, username, "brand-new-password")
  await expect(other.getByRole("heading", { name: "Dashboard" })).toBeVisible()
  await context.close()
})

test("deletes a user", async ({ page, api }) => {
  const username = unique("deluser")
  await api.createUser(username, PASSWORD)
  await page.goto("/settings/users")
  await page.getByRole("row").filter({ hasText: username }).getByRole("button", { name: "Delete" }).click()
  await expect(dialog(page)).toContainText(`${username} will be deleted`)
  await dialog(page).getByRole("button", { name: "Delete user" }).click()
  await expect(page.getByText("User deleted")).toBeVisible()
  await expect(page.getByRole("row").filter({ hasText: username })).toHaveCount(0)
})
